// ── 회전 동역학 ────────────────────────────────────────────────
//
//   dω/dt = -sign(ω)·TAU_COULOMB
//           - B_VISCOUS·ω
//           - C_DRAG·ω·|ω|
//           - TAU_BRAKE·sign(ω)·isBraking
//   θ += ω·dt

/** 베어링 정지 마찰 [rad/s²]. 속도와 무관한 일정 감속 — 저속 구간의 정지를 만든다. */
export const TAU_COULOMB = 0.35;

/** 점성 마찰 계수 [1/s]. 속도에 비례하는 감속 (윤활유·베어링 내부 저항). */
export const B_VISCOUS = 0.08;

/** 공기 저항 계수 [1/rad]. 속도의 제곱에 비례 — 고속 구간의 감속을 지배한다. */
export const C_DRAG = 0.004;

/** 손가락 브레이크의 추가 감속 [rad/s²]. 브레이크 중에만 더해진다. */
export const TAU_BRAKE = 4.0;

/** 각속도 상한 [rad/s]. 210 rad/s ≈ 2005 RPM. 양·음 양쪽에 대칭으로 적용한다. */
export const OMEGA_MAX = 210;

/** 정지 스냅 문턱 [rad/s]. |ω| 가 이 값 밑으로 내려가면 정확히 0 으로 떨어뜨린다.
 *  이게 없으면 쿨롱 마찰이 매 스텝 부호를 뒤집어 스피너가 미세하게 떠는 것처럼 보인다. */
export const OMEGA_STOP = 0.15;

// ── 시뮬레이션 타이밍 ──────────────────────────────────────────

/** 고정 타임스텝 [s]. 240Hz. 프레임레이트가 흔들려도 물리는 항상 이 간격으로만 전진한다. */
export const FIXED_DT = 1 / 240;

/** 한 프레임에 소화할 수 있는 최대 서브스텝 수 (death spiral 방지).
 *  5 × FIXED_DT ≈ 20.8ms — 60fps 프레임(16.7ms)에 1스텝의 여유가 있다. */
export const MAX_SUBSTEPS = 5;

// ── 입력 모델 (포인터 샘플 → 각속도) ───────────────────────────

/** 플릭 속도 추정에 쓰는 시간 윈도 [ms]. 마지막 샘플 기준 이 범위 안의 샘플만 본다.
 *  길게 잡으면 손가락을 대고 있다가 튕긴 동작에서 "머무른 구간"이 속도를 희석시킨다. */
export const FLICK_SAMPLE_WINDOW_MS = 100;

/** 윈도 안에서 실제로 사용할 최대 샘플 수. 최근 것부터 이 개수까지만 쓴다. */
export const FLICK_MAX_SAMPLES = 5;

/** 플릭 게인 [무차원]. 손가락의 각속도(v_tangential / r)를 스피너 각속도 증가분으로 바꾸는 배율.
 *
 *  근거: 강한 플릭은 접선 방향으로 대략 900 px/s, 회전 중심에서 130px 떨어진 지점에서 일어난다.
 *  → 손가락 각속도 ≈ 6.9 rad/s → Δω ≈ 125 rad/s ≈ 1190 RPM (기분 좋은 한 방, 상한까지는 여유).
 *  아주 빠른 플릭(≈1600 px/s)이면 OMEGA_MAX 에 닿는다.
 *
 *  TODO(Phase 6): 실기기 튜닝 대상. 손가락 크기·화면 크기·터치 샘플링 레이트에 따라 체감이
 *  달라지므로 실제 안드로이드 기기에서 확정한다. 물리 상수가 아니므로 감속 골든 스냅샷에는
 *  영향이 없지만, 바꿀 때는 DECISIONS.md 에 전후 값을 남긴다. */
export const K_FLICK = 18;

/** 플릭 지렛대 길이의 하한 (스피너 반경 대비 비율).
 *  Δω 는 1/r 에 비례하므로 회전 중심 바로 위를 문지르면 값이 발산한다.
 *  중심에서 이 비율보다 가까운 지점의 입력은 이 거리에서 일어난 것으로 취급한다. */
export const FLICK_MIN_LEVER_ARM_FRAC = 0.15;
